    private val byCode: Map<String, Currency> =
        entries.associate { it.code to Currency(it.code, it.scale, it.symbol, it.name) }

    /** All registry currencies, ordered by code. */
    val all: List<Currency> = byCode.values.sortedBy { it.code }

    fun findOrNull(code: String): Currency? = byCode[code]

    /** Returns the currency for [code], or throws [UnknownCurrencyException]. */
    fun get(code: String): Currency = byCode[code] ?: throw UnknownCurrencyException(code)
